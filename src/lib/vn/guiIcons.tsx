export type GuiIconName = keyof typeof GUI_ICON_MAP | string;

function renderMaskOrImage(url: string, className: string, alt: string, style?: React.CSSProperties) {
  const isSvg = url.endsWith('.svg') || url.includes('.svg');
  if (isSvg) {
    return (
      <span
        role="img"
        aria-label={alt}
        className={`inline-block bg-current shrink-0 select-none ${className}`}
        style={{
          maskImage: `url("${url}")`,
          maskRepeat: 'no-repeat',
          maskPosition: 'center',
          maskSize: 'contain',
          WebkitMaskImage: `url("${url}")`,
          WebkitMaskRepeat: 'no-repeat',
          WebkitMaskPosition: 'center',
          WebkitMaskSize: 'contain',
          ...style,
        }}
      />
    );
  }
  return (
    <img
      src={url}
      alt={alt}
      className={`inline-block object-contain shrink-0 select-none ${className}`}
      loading="lazy"
      draggable={false}
      style={style}
    />
  );
}

/**
 * Componente declarativo para renderizar un icono SVG por clave o ruta
 */
export function GuiIcon({
  name,
  className = 'w-3.5 h-3.5',
  alt = 'icono',
  size,
  style,
}: {
  name: GuiIconName;
  className?: string;
  alt?: string;
  size?: number;
  style?: React.CSSProperties;
}) {
  const computedStyle: React.CSSProperties = {
    ...(size ? { width: `${size}px`, height: `${size}px`, minWidth: `${size}px`, minHeight: `${size}px` } : {}),
    ...style,
  };
  const url = GUI_ICON_MAP[name] || (name.startsWith('/') || name.startsWith('http') ? name : null);

  if (url) {
    return renderMaskOrImage(url, className, alt, computedStyle);
  }

  // Fallback seguro
  return <span style={computedStyle} className={`inline-block shrink-0 select-none ${className}`}>{name}</span>;
}

/**
 * Componente para renderizar un icono SVG o fallback con resolución inteligente de emojis
 */
export function GuiIconRenderer({
  icon,
  className = 'w-4 h-4',
  alt = 'icono',
  size,
  style,
}: {
  icon?: string;
  className?: string;
  alt?: string;
  size?: number;
  style?: React.CSSProperties;
}) {
  if (!icon) return null;

  const computedStyle: React.CSSProperties = {
    ...(size ? { width: `${size}px`, height: `${size}px`, minWidth: `${size}px`, minHeight: `${size}px` } : {}),
    ...style,
  };

  // 1. Si está en el mapa de iconos (por nombre o emoji)
  if (GUI_ICON_MAP[icon]) {
    return renderMaskOrImage(GUI_ICON_MAP[icon], className, alt, computedStyle);
  }

  // 2. Si es una ruta directa a SVG o imagen
  if (icon.startsWith('/') || icon.startsWith('http') || icon.includes('.svg') || icon.includes('.png')) {
    return renderMaskOrImage(icon, className, alt, computedStyle);
  }

  // 3. Fallback si no hay icono SVG coincidente
  return <span style={computedStyle} className={`inline-block shrink-0 select-none ${className}`}>{icon}</span>;
}
